def plan_sweep(cell_list=None, target_sets=(DEFAULT_TARGET_SET,),
               ranks=(DEFAULT_RANK,), tag=DEFAULT_TAG, gpus=8, epochs=6.0,
               grad_accum=4, sec_per_step=SEC_PER_OPTIM_STEP, manifest=None,
               write_yaml=False, fh=None):
    """The Phase-1/Phase-2 job list with an estimated cost, printed as a table.

    Phase 1 (4.5's injection-site sweep) is this with one cell and many
    (target_set, rank) pairs; Phase 2 is this with all cells and one pair.
    """
    fh = fh or sys.stdout
    jobs = make_jobs(cell_list, target_sets, ranks, tag=tag, gpus=gpus,
                     epochs=epochs, grad_accum=grad_accum, manifest=manifest,
                     write_yaml=write_yaml)
    print("sweep plan: %d job(s)  |  %d cell(s) x %d target set(s) x %d rank(s)"
          % (len(jobs), len(set(j.cell.key for j in jobs)), len(target_sets),
             len(ranks)), file=fh)
    print("  gpus/job=%d  epochs=%g  grad_accum=%d  sec/optim-step=%g (ASSUMPTION)"
          % (gpus, epochs, grad_accum, sec_per_step), file=fh)
    print("", file=fh)
    hdr = ("  %-10s %-14s %5s %7s %12s %8s %10s %9s"
           % ("cell", "targets", "rank", "sites", "lora params", "samples",
              "opt steps", "gpu-hrs"))
    print(hdr, file=fh)
    print("  " + "-" * (len(hdr) - 2), file=fh)
    total_h, total_steps = 0.0, 0
    for j in jobs:
        h = j.gpu_hours(sec_per_step)
        total_h += h
        total_steps += j.optim_steps()
        print("  %-10s %-14s %5d %7d %12s %8d %10d %9.1f"
              % (j.cell.key, j.target_set, j.rank, j.n_sites,
                 "{:,}".format(j.n_params), j.n_samples, j.optim_steps(), h),
              file=fh)
    print("  " + "-" * (len(hdr) - 2), file=fh)
    print("  %-10s %-14s %5s %7s %12s %8s %10d %9.1f"
          % ("TOTAL", "", "", "", "", "", total_steps, total_h), file=fh)
    print("", file=fh)
    print("  ~%.1f GPU-hours (~%.1f wall-hours on %d GPUs, serial)."
          % (total_h, total_h / max(1, gpus), gpus), file=fh)
    thin = [j for j in jobs if j.optim_steps() < 50]
    if thin:
        print("", file=fh)
        print("  WARNING: %d job(s) get fewer than 50 optimizer steps "
              "(min %d, cell %s)."
              % (len(thin), min(j.optim_steps() for j in thin),
                 min(jobs, key=lambda j: j.optim_steps()).cell.key), file=fh)
        print("  A cell has only a few hundred samples and the effective batch "
              "here is %d (grad_accum %d x %d GPUs),"
              % (grad_accum * gpus, grad_accum, gpus), file=fh)
        print("  so a per-cell LoRA sees almost no updates. Fix by lowering "
              "--grad-accum (to 1) and/or raising", file=fh)
        print("  --epochs; the Phase-1 kill criterion ('no injection-site "
              "configuration lets plain LoRA improve a", file=fh)
        print("  single version') is only meaningful once the optimizer has "
              "actually run.", file=fh)
    print("  The 6.2 transfer matrix on top of this is |cells|^2 evaluations, "
          "not trainings.", file=fh)
    return jobs


