def _cells_arg(spec):
    from .bcdata import _cells_arg as f
    return f(spec)


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Phase-2 per-cell LoRA jobs (adapterCL.md 7)")
    sub = ap.add_subparsers(dest="cmd")

    def common(p):
        p.add_argument("--cells", default="all")
        p.add_argument("--tag", default=DEFAULT_TAG)
        p.add_argument("--targets", default=DEFAULT_TARGET_SET,
                       help="comma list of target-set names (%s)"
                            % ",".join(targets.TARGET_SETS))
        p.add_argument("--ranks", default=str(DEFAULT_RANK))
        p.add_argument("--gpus", type=int, default=8)
        p.add_argument("--epochs", type=float, default=6.0)
        p.add_argument("--grad-accum", type=int, default=4)
        p.add_argument("--manifest", default=None,
                       help="bcdata.build_cell_corpora manifest.json")
        return p

    p = common(sub.add_parser("sweep", help="print the job plan + cost"))
    p.add_argument("--sec-per-step", type=float, default=SEC_PER_OPTIM_STEP)
    p.add_argument("--write-yaml", action="store_true")

    p = common(sub.add_parser("yaml", help="generate the per-cell YAMLs"))

    p = common(sub.add_parser("commands", help="print the training commands"))
    p.add_argument("--launcher", nargs="?", const="", default=None,
                   help="also write a launcher script (optional path)")

    p = common(sub.add_parser("run", help="dry-run by default"))
    p.add_argument("--execute", action="store_true",
                   help="actually launch (needs a GPU; use tmux on an "
                        "allocation)")

    p = sub.add_parser("collect", help="collect + validate trained adapters")
    p.add_argument("--cells", default="all")
    p.add_argument("--tag", default=DEFAULT_TAG)
    p.add_argument("--no-validate", action="store_true")

    args = ap.parse_args(argv)
    cmd = args.cmd or "sweep"

    if cmd == "collect":
        collect_adapters(args.tag, _cells_arg(args.cells),
                         validate=not args.no_validate)
        return 0

    manifest = None
    if getattr(args, "manifest", None):
        with open(args.manifest) as fh:
            manifest = json.load(fh)
    tsets = tuple(t.strip() for t in args.targets.split(",") if t.strip())
    ranks = tuple(int(r) for r in args.ranks.split(",") if r.strip())
    cell_list = _cells_arg(args.cells)

    if cmd == "sweep":
        plan_sweep(cell_list, tsets, ranks, tag=args.tag, gpus=args.gpus,
                   epochs=args.epochs, grad_accum=args.grad_accum,
                   sec_per_step=args.sec_per_step, manifest=manifest,
                   write_yaml=args.write_yaml)
        return 0

    jobs = make_jobs(cell_list, tsets, ranks, tag=args.tag, gpus=args.gpus,
                     epochs=args.epochs, grad_accum=args.grad_accum,
                     manifest=manifest, write_yaml=(cmd != "run") or True)
    if cmd == "yaml":
        for j in jobs:
            print("%-24s %s" % (j.name, j.yaml_path))
        return 0
    if cmd == "commands":
        for rec in build_commands(jobs, gpus=args.gpus):
            print("")
            print("# %s" % rec["job"].name)
            print(rec["cmd"])
        if args.launcher is not None:
            path = write_launcher(jobs, args.launcher or None, gpus=args.gpus)
            print("\nlauncher: %s" % path)
        return 0
    if cmd == "run":
        run(jobs, execute=args.execute, gpus=args.gpus)
        return 0

    ap.print_help()
    return 1


if __name__ == "__main__":
    sys.exit(main())
