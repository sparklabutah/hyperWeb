"""Phase-2 per-cell LoRA training: one adapter per (environment, era) cell.

adapterCL.md 7 Phase 2 asks for "one LoRA per (environment, era) cell -- 18
cells", which the 6.2 transfer matrix then cross-applies. This module produces
the LLaMA-Factory jobs that do it: one generated YAML per cell, the exact shell
commands to run them, a cost table for the Phase-1 sweep, and a collector that
validates what came back.

It follows `self-correct/sft_cell.sh`'s pattern -- LLaMA-Factory here is
YAML-only (it rejects CLI overrides), so every run needs its own file -- but does
the generation in python instead of `sed`, because a LoRA recipe changes more
fields than a sed chain can safely carry, and because `lora_target` has to come
from `targets.peft_target_modules()` rather than from `all` (4.5: `all` is unsafe
on this hybrid architecture -- it would match the vision tower and `conv1d`,
which vLLM silently drops at serve time).

Three deliberate differences from `sft_cell.sh`:

* **Generated YAMLs live in `out/cells/<tag>/yaml/`, not in the LLaMA-Factory
  tree.** `lmf train` takes an absolute path, and the parent repo already has 40+
  `_gen_*.yaml` files from other experiments; adding 18 more per sweep is a
  merge hazard. Relative paths *inside* the YAML (deepspeed) are resolved against
  the CWD, so the commands `cd` into LLaMA-Factory anyway and we write the
  deepspeed path absolute for good measure.
* **`dataset_dir` points at our own registry** (`bcdata.local_dataset_info()`),
  so no adapterCL dataset has to be added to the shared
  `LLaMA-Factory/data/dataset_info.json`.
* **`output_dir` is absolute**, under `paths.OUT_CELLS`, so
  `materialize.cell_adapter_dir()` and `collect_adapters()` agree without
  copying anything out of `LLaMA-Factory/saves`.

Pure stdlib -- importable from the system python (3.6+). `collect_adapters` will
use `materialize.read_adapter` (torch/safetensors) when available and fall back
to a structural check when it is not.
"""

