#: The full-SFT recipe this is derived from. Read it before changing anything
#: here -- it encodes hard-won memory settings for Qwen3.5-9B at 64k context.
BASE_RECIPE = os.path.join(paths.LLAMA_FACTORY, "examples", "train_full",
                           "_gen_tw-qwen35-9b.yaml")

#: DeepSpeed configs, absolute. ZeRO-3 *without* CPU offload is the default for
#: LoRA: offload exists in the full-SFT recipe to move 9B x (fp32 master + Adam
#: moments) off the GPU, but a LoRA's optimizer state is ~10 MB, so offload buys
#: nothing and costs a CPUAdam JIT build plus a slow optimizer step.
DS_Z3 = os.path.join(paths.LLAMA_FACTORY, "examples", "deepspeed",
                     "ds_z3_config.json")
DS_Z3_OFFLOAD = os.path.join(paths.LLAMA_FACTORY, "examples", "deepspeed",
                             "ds_z3_offload_config.json")

#: Chat template per backbone family, keyed by the substring that identifies it
#: in the model id. A WRONG TEMPLATE DOES NOT ERROR -- LLaMA-Factory happily
#: wraps the conversation in the other family's delimiters, the loss curve looks
#: ordinary, and the adapter comes out useless. So the default is not a guess:
#: `template_for` raises on a model it does not recognise, and the caller must
#: pass `template=` explicitly to override.
TEMPLATE_FOR = (
    ("qwen3.5", "qwen3_5"),
    ("qwen3_5", "qwen3_5"),
    ("llama-3.1", "llama3"),
    ("llama-3.2", "llama3"),
    ("llama-3.3", "llama3"),
)
DEFAULT_TEMPLATE = "qwen3_5"


def template_for(model):
    """LLaMA-Factory `template:` for a model id. Raises on an unknown family."""
    m = (model or "").lower()
    for needle, tpl in TEMPLATE_FOR:
        if needle in m:
            return tpl
    raise ValueError(
        "no chat template known for model %r -- add it to percell.TEMPLATE_FOR "
        "or pass template= explicitly. Guessing here would train the adapter "
        "on mis-delimited text with no error anywhere." % (model,))


DEFAULT_TAG = "percell"
DEFAULT_RANK = 16
DEFAULT_TARGET_SET = "attn_mlp"

#: Throughput assumption for the cost table. THIS IS A PLACEHOLDER: measure it in
#: Phase 1 with a single cell and pass --sec-per-step. At 64k cutoff on H200s the
#: full-SFT recipe ran on the order of tens of seconds per optimizer step; LoRA
#: removes the optimizer/communication cost but not the activations.
SEC_PER_OPTIM_STEP = 25.0

YAML_TEMPLATE = """\
### adapterCL Phase 2 -- per-cell LoRA. GENERATED by adaptercl/percell.py; do not hand-edit.
### cell        : %(cell_key)s   (env=%(env)s era=%(era)s theme=%(theme)s year=%(year)s)
### generated   : %(created)s
### derived from: %(base_recipe)s
### Every line marked DEVIATION differs from that full-SFT recipe; everything else is copied.
model_name_or_path: %(model)s
trust_remote_code: true

### method
stage: sft
do_train: true
finetuning_type: lora                     # DEVIATION: full -> lora (7 Phase 2 wants per-cell adapters)
lora_rank: %(rank)d
lora_alpha: %(alpha)g
lora_dropout: %(dropout)g
lora_target: %(lora_target)s   # DEVIATION: explicit list from targets.peft_target_modules(%(target_set)r).
                                          # NEVER `all`: it would match the vision tower and conv1d,
                                          # and vLLM drops LoRAs on non-Linear modules silently (4.5).
deepspeed: %(deepspeed)s   # DEVIATION: ZeRO-3 *without* CPU offload -- a LoRA optimizer state is tiny
flash_attn: fa2
enable_liger_kernel: true                 # as in the base recipe: fused CE keeps the 152k-vocab logits off-peak

### dataset
dataset: %(dataset)s
dataset_dir: %(dataset_dir)s   # DEVIATION: adapterCL's own registry, not LLaMA-Factory/data
template: %(template)s   # per-backbone; see TEMPLATE_FOR -- a wrong one trains on mis-delimited text and never errors
cutoff_len: %(cutoff)d                       # unchanged: TimeWarp AXTree prompts are genuinely this long
max_samples: %(max_samples)d
preprocessing_num_workers: 16
dataloader_num_workers: 4

### output
output_dir: %(output_dir)s
logging_steps: %(logging_steps)d                         # DEVIATION: 10 -> %(logging_steps)d, a cell is only ~%(steps_hint)d steps
save_strategy: epoch
plot_loss: true
overwrite_output_dir: true
save_only_model: true                     # DEVIATION: no optimizer state; we only ever reload the adapter
report_to: none

### train
per_device_train_batch_size: 1
gradient_accumulation_steps: %(grad_accum)d
learning_rate: %(lr)s                    # DEVIATION: 1.0e-5 -> %(lr)s (standard LoRA lr; the full-SFT lr underfits an adapter)
num_train_epochs: %(epochs)g                    # DEVIATION: 5 -> %(epochs)g; a cell has ~%(n_samples)d samples, so an epoch is a handful of steps
lr_scheduler_type: cosine
warmup_ratio: 0.1
bf16: true
fp16: false
ddp_timeout: 180000000
resume_from_checkpoint: null
gradient_checkpointing: true
seed: %(seed)d
data_seed: %(seed)d
%(eval_block)s"""

EVAL_BLOCK = """
### eval
val_size: %(val_size)g
per_device_eval_batch_size: 1
eval_strategy: steps
eval_steps: %(eval_steps)d
"""

#: Substituted as a *value* into YAML_TEMPLATE, so it is not %-formatted itself:
#: percent signs here must be single.
NO_EVAL_BLOCK = """
### eval -- DEVIATION: disabled. The base recipe holds out 10% of a ~4k-sample pooled
### corpus; a cell has a few hundred samples, so a 10% split is both a material loss of
### training data and too small to read. Validate by cross-applying adapters (6.2) instead.
"""


