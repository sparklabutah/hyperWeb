def _structural_check(adapter_dir):
    """Adapter sanity without torch: config parses and a weight file exists."""
    cfg_path = os.path.join(adapter_dir, "adapter_config.json")
    if not os.path.exists(cfg_path):
        return None, "no adapter_config.json"
    try:
        with open(cfg_path) as fh:
            cfg = json.load(fh)
    except ValueError as exc:
        return None, "unreadable adapter_config.json: %s" % exc
    for name in ("adapter_model.safetensors", "adapter_model.bin"):
        if os.path.exists(os.path.join(adapter_dir, name)):
            return cfg, None
    return cfg, "no adapter weights"


def collect_adapters(tag=DEFAULT_TAG, cell_list=None, root=None, validate=True,
                     quiet=False):
    """Map cell -> adapter dir for a finished sweep, validating each one.

    LLaMA-Factory writes the adapter at the top of `output_dir` and a copy per
    epoch under `checkpoint-*`; we prefer the top-level one and fall back to the
    highest-numbered checkpoint (which is what you get if the run was killed
    after an epoch but before `save_model`).
    """
    cell_list = list(cell_list or cells.ALL_CELLS)
    found, missing, bad = collections.OrderedDict(), [], collections.OrderedDict()
    reader = None
    if validate:
        try:
            from . import materialize
            reader = materialize.read_adapter
        except ImportError as exc:      # torch/safetensors absent (py3.6)
            if not quiet:
                print("NOTE: materialize.read_adapter unavailable (%s); "
                      "falling back to a structural check." % exc)

    for c in cell_list:
        d = cell_output_dir(c, tag, root=root)
        cand = d
        if not os.path.exists(os.path.join(d, "adapter_config.json")):
            ckpts = []
            if os.path.isdir(d):
                for name in os.listdir(d):
                    if name.startswith("checkpoint-") and name[11:].isdigit():
                        ckpts.append((int(name[11:]), os.path.join(d, name)))
            cand = sorted(ckpts)[-1][1] if ckpts else None
        if cand is None:
            missing.append(c.key)
            continue
        cfg, err = _structural_check(cand)
        if err:
            bad[c.key] = "%s (%s)" % (err, cand)
            continue
        rec = {"dir": cand, "r": cfg.get("r"),
               "lora_alpha": cfg.get("lora_alpha"),
               "target_modules": cfg.get("target_modules")}
        if reader is not None:
            try:
                factors, cfg2, meta = reader(cand)
                rec["n_sites"] = len(factors)
                rec["n_params"] = sum(int(A.numel()) + int(B.numel())
                                      for A, B in factors.values())
                rec["validated"] = "read_adapter"
            except ImportError as exc:
                # materialize imports torch/safetensors lazily *inside* its
                # functions, so the import above succeeds under python 3.6 and
                # only the call fails. That is an environment limitation, not a
                # bad adapter -- degrade to the structural check.
                if not quiet:
                    print("NOTE: read_adapter needs %s; falling back to a "
                          "structural check (run under %s for the full check)."
                          % (exc, paths.PY_TRAIN))
                reader = None
                rec["validated"] = "structural"
            except Exception as exc:               # noqa: BLE001 - report, don't hide
                bad[c.key] = "read_adapter failed: %s (%s)" % (exc, cand)
                continue
        else:
            rec["validated"] = "structural"
        found[c.key] = rec

    if not quiet:
        print("adapters for tag %r under %s" % (tag, root or paths.OUT_CELLS))
        for key, rec in found.items():
            print("  %-10s r=%-3s sites=%-4s params=%-12s %s"
                  % (key, rec.get("r"), rec.get("n_sites", "-"),
                     "{:,}".format(rec["n_params"]) if "n_params" in rec else "-",
                     rec["dir"]))
        if bad:
            for key, why in bad.items():
                print("  %-10s INVALID: %s" % (key, why))
        if missing:
            print("  missing (%d): %s" % (len(missing), ", ".join(missing)))
        print("  %d/%d cells present" % (len(found), len(cell_list)))
    return {"tag": tag, "found": found, "missing": missing, "invalid": bad}


