def env_preamble(extra=None):
    """The spack toolchain LLaMA-Factory training needs.

    Without `SPACK_GCC_BIN` on PATH and `CUDA_HOME` pointing at the cu130
    toolkit, DeepSpeed's CPUAdam JIT build fails (torch here is a cu130 build and
    the system CUDA is 12.5) and tilelang's Qwen3.5 FLA kernels will not compile
    under system g++ 8.5. Copied from LLaMA-Factory/run.sh and
    self-correct/sft_cell.sh, but using paths.SPACK_* (the *current* spack tree --
    sft_cell.sh still names the v10 tree, which has moved).
    """
    lines = []
    if paths.SPACK_GCC_BIN:
        lines.append('export PATH="%s:$PATH"' % paths.SPACK_GCC_BIN)
    if paths.SPACK_CUDA_HOME:
        lines.extend(('export CUDA_HOME="%s"' % paths.SPACK_CUDA_HOME,
                      'export PATH="$CUDA_HOME/bin:$PATH"'))
    lines.extend(('export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True',
                  'export FORCE_TORCHRUN=1',
                  'export DISABLE_VERSION_CHECK=1'))
    lines.extend(extra or [])
    return lines


def build_commands(jobs, gpus=None, cuda_visible_devices=None, log_dir=None):
    """Exact shell commands to train each job, preamble included.

    Returns [{"job", "cmd", "log"}]. `cmd` is a single `bash -c`-safe string:
    LLaMA-Factory resolves relative paths against the CWD, so it cds into the
    LLaMA-Factory root even though our YAML/output paths are absolute.
    """
    log_dir = log_dir or os.path.join(paths.OUT_LOGS, "percell")
    out = []
    for j in jobs:
        pre = list(env_preamble())
        if cuda_visible_devices:
            pre.append('export CUDA_VISIBLE_DEVICES=%s' % cuda_visible_devices)
        if gpus:
            pre.append('export NPROC_PER_NODE=%d' % gpus)
        log = os.path.join(log_dir, "%s.log" % j.name)
        cmd = "; ".join(pre + ['cd "%s"' % paths.LLAMA_FACTORY,
                               '"%s" train "%s"' % (paths.LMF, j.yaml_path)])
        out.append({"job": j, "cmd": cmd, "log": log})
    return out


def write_launcher(jobs, path=None, gpus=None, cuda_visible_devices=None,
                   log_dir=None):
    """Write a runnable bash script for the whole sweep (still not launched)."""
    path = path or os.path.join(paths.OUT_CELLS, "run_percell.sh")
    d = os.path.dirname(path)
    if d and not os.path.isdir(d):
        os.makedirs(d)
    log_dir = log_dir or os.path.join(paths.OUT_LOGS, "percell")
    if not os.path.isdir(log_dir):
        os.makedirs(log_dir)
    cmds = build_commands(jobs, gpus=gpus,
                          cuda_visible_devices=cuda_visible_devices,
                          log_dir=log_dir)
    lines = ["#!/usr/bin/env bash",
             "# GENERATED by adaptercl/percell.py on %s"
             % datetime.datetime.now().isoformat(),
             "# Run this inside a tmux window on an allocation, never on the "
             "login node.",
             "set -uo pipefail", ""]
    for rec in cmds:
        j = rec["job"]
        lines.append('echo "==== %s (%d samples, %d optim steps) ===="'
                     % (j.name, j.n_samples, j.optim_steps()))
        lines.append("( %s ) 2>&1 | tee %s" % (rec["cmd"], rec["log"]))
        lines.append("")
    with open(path, "w") as fh:
        fh.write("\n".join(lines))
    os.chmod(path, 0o755)
    return path


def run(jobs, execute=False, gpus=None, cuda_visible_devices=None,
        log_dir=None):
    """Dry-run by default. Refuses to launch without `execute=True`.

    Even with `execute=True` it checks for a visible GPU first: launching a 9B
    LoRA on a login node is the failure mode this guard exists for.
    """
    cmds = build_commands(jobs, gpus=gpus,
                          cuda_visible_devices=cuda_visible_devices,
                          log_dir=log_dir)
    if not execute:
        print("DRY RUN -- %d job(s). Nothing launched. Pass execute=True "
              "(CLI: --execute) to run, and do it inside tmux on an "
              "allocation." % len(cmds))
        for rec in cmds:
            print("")
            print("# %s -> %s" % (rec["job"].name, rec["job"].output_dir))
            print(rec["cmd"])
        return {"executed": False, "commands": [c["cmd"] for c in cmds]}

    try:
        subprocess.check_output(["nvidia-smi", "-L"])
    except (OSError, subprocess.CalledProcessError):
        raise RuntimeError(
            "no GPU visible (nvidia-smi -L failed). Refusing to launch %d "
            "LLaMA-Factory job(s). Allocate a node first." % len(cmds))
    results = []
    for rec in cmds:
        d = os.path.dirname(rec["log"])
        if not os.path.isdir(d):
            os.makedirs(d)
        print("==== %s ====" % rec["job"].name)
        with open(rec["log"], "w") as fh:
            rc = subprocess.call(["bash", "-c", rec["cmd"]], stdout=fh,
                                 stderr=subprocess.STDOUT)
        print("  rc=%d  log=%s" % (rc, rec["log"]))
        results.append({"job": rec["job"].name, "rc": rc, "log": rec["log"]})
    return {"executed": True, "results": results}


