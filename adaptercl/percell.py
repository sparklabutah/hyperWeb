class CellJob(object):
    """One LLaMA-Factory LoRA run for one cell."""

    __slots__ = ("cell", "dataset", "dataset_dir", "target_set", "rank",
                 "alpha", "tag", "yaml_path", "output_dir", "n_samples",
                 "epochs", "grad_accum", "gpus", "n_sites", "n_params", "seed")

    def __init__(self, cell, dataset, target_set, rank, alpha, tag, yaml_path,
                 output_dir, n_samples=0, epochs=6.0, grad_accum=4, gpus=8,
                 n_sites=0, n_params=0, dataset_dir=None, seed=42):
        self.cell = cell
        self.dataset = dataset
        self.dataset_dir = dataset_dir
        self.target_set = target_set
        self.rank = rank
        self.alpha = alpha
        self.tag = tag
        self.yaml_path = yaml_path
        self.output_dir = output_dir
        self.n_samples = n_samples
        self.epochs = epochs
        self.grad_accum = grad_accum
        self.gpus = gpus
        self.n_sites = n_sites
        self.n_params = n_params
        self.seed = seed

    @property
    def name(self):
        return "%s__%s__r%d" % (self.cell.key, self.target_set, self.rank)

    def optim_steps(self):
        per_step = max(1, self.grad_accum * max(1, self.gpus))
        return int(round(self.n_samples * self.epochs / float(per_step)))

    def gpu_hours(self, sec_per_step=SEC_PER_OPTIM_STEP):
        return self.optim_steps() * sec_per_step * max(1, self.gpus) / 3600.0

    def as_dict(self):
        return {"cell": self.cell.key, "dataset": self.dataset,
                "dataset_dir": self.dataset_dir,
                "target_set": self.target_set, "rank": self.rank,
                "alpha": self.alpha, "tag": self.tag, "yaml": self.yaml_path,
                "output_dir": self.output_dir, "n_samples": self.n_samples,
                "epochs": self.epochs, "gpus": self.gpus,
                "n_sites": self.n_sites, "n_params": self.n_params,
                "optim_steps": self.optim_steps(), "seed": self.seed}

    def __repr__(self):
        return "CellJob(%s)" % self.name


def cell_output_dir(cell, tag=DEFAULT_TAG, root=None):
    """Where this cell's adapter lands. Mirrors materialize.cell_adapter_dir."""
    return os.path.join(root or paths.OUT_CELLS, tag, cell.key)


def cell_yaml_path(cell, tag=DEFAULT_TAG, root=None):
    return os.path.join(root or paths.OUT_CELLS, tag, "yaml",
                        "_gen_%s.yaml" % cell.key)


