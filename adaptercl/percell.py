def _env_label(unit):
    """Provenance text for the unit's environment axis.

    Unchanged for Cell ("wiki") and Version ("all"); a Site names itself and,
    for the pooled units, which sites it can draw from.
    """
    if getattr(unit, "granularity", None) == "site":
        if unit.env is not None:
            return unit.site
        return "%s(%s)" % (unit.site, ",".join(unit.sites))
    return unit.env if unit.env is not None else "all"


def _era_label(unit):
    """Provenance text for the unit's era axis: "3" for a Cell, "1-6" for a
    Site pooled over every era, "6" for an era-restricted Site, "2,4,6" for a
    non-contiguous set."""
    if unit.era is not None:
        return unit.era
    eras = getattr(unit, "eras", None)
    if not eras:
        return "all"
    eras = list(eras)
    if len(eras) == 1:
        return "%d" % eras[0]
    if eras == list(range(eras[0], eras[-1] + 1)):
        return "%d-%d" % (eras[0], eras[-1])
    return ",".join(str(e) for e in eras)


def write_cell_yaml(cell, dataset, target_set=DEFAULT_TARGET_SET,
                    rank=DEFAULT_RANK, alpha=None, out_dir=None, tag=DEFAULT_TAG,
                    model=None, epochs=6.0, lr="1.0e-4", cutoff=65536,
                    grad_accum=4, dropout=0.0, seed=42, val_size=0.0,
                    eval_steps=50, max_samples=100000, deepspeed=None,
                    dataset_dir=None, n_samples=0, yaml_path=None,
                    logging_steps=2, template=None):
    """Generate one per-cell LoRA YAML and return its path.

    `alpha` defaults to 2*rank (the PEFT convention this repo's other LoRA runs
    use); `dataset_dir` defaults to adapterCL's own registry so nothing has to be
    written into the shared LLaMA-Factory dataset_info.json.
    """
    from . import bcdata            # local: bcdata imports subprocess/shutil only

    alpha = float(2 * rank if alpha is None else alpha)
    out_dir = out_dir or cell_output_dir(cell, tag)
    yaml_path = yaml_path or cell_yaml_path(cell, tag)
    dataset_dir = dataset_dir or os.path.dirname(bcdata.local_dataset_info())
    deepspeed = deepspeed or DS_Z3
    for d in (os.path.dirname(yaml_path), out_dir):
        if not os.path.isdir(d):
            os.makedirs(d)

    modules = targets.peft_target_modules(target_set)
    body = YAML_TEMPLATE % {
        # A Version has no single env/theme -- it pools all three sites for its
        # era -- and a Site has no single era, so render those provenance fields
        # from what the unit exposes. `era` is formatted with %s, not %d, for
        # exactly that reason (a Site's era is None); for a Cell or Version the
        # rendered text is unchanged.
        "cell_key": cell.key,
        "env": _env_label(cell),
        "era": _era_label(cell),
        "theme": (cell.theme if hasattr(cell, "theme")
                  else ", ".join("%s=%s" % kv for kv in
                                 sorted(cell.themes.items()))),
        "year": cell.year,
        "created": datetime.datetime.now().isoformat(),
        "base_recipe": BASE_RECIPE,
        "model": model or paths.BASE_MODEL,
        "template": template or template_for(model or paths.BASE_MODEL),
        "rank": int(rank), "alpha": alpha, "dropout": float(dropout),
        "lora_target": ",".join(modules), "target_set": target_set,
        "deepspeed": deepspeed,
        "dataset": dataset, "dataset_dir": dataset_dir,
        "cutoff": int(cutoff), "max_samples": int(max_samples),
        "output_dir": out_dir, "logging_steps": int(logging_steps),
        "steps_hint": max(1, int(n_samples * epochs / max(1, grad_accum * 8))),
        "grad_accum": int(grad_accum), "lr": lr, "epochs": float(epochs),
        "n_samples": int(n_samples), "seed": int(seed),
        "eval_block": (EVAL_BLOCK % {"val_size": val_size,
                                     "eval_steps": int(eval_steps)}
                       if val_size and val_size > 0 else NO_EVAL_BLOCK),
    }
    with open(yaml_path, "w") as fh:
        fh.write(body)
    return yaml_path


def make_jobs(cell_list=None, target_sets=(DEFAULT_TARGET_SET,),
              ranks=(DEFAULT_RANK,), tag=DEFAULT_TAG, manifest=None,
              gpus=8, epochs=6.0, grad_accum=4, write_yaml=True, seed=42,
              cfg=None, **yaml_kw):
    """Build the job list (and, by default, the YAMLs) for a sweep.

    `manifest` is the dict written by `bcdata.build_cell_corpora`; without it we
    fall back to the census for sample counts and to the conventional dataset
    name `adaptercl_<tag>_<cell>`, so the plan can be costed before any corpus
    exists.
    """
    from . import bcdata

    cell_list = list(cell_list or cells.ALL_CELLS)
    if cfg is None:
        try:
            cfg = targets.load_text_config()
        except (IOError, KeyError) as exc:
            print("NOTE: could not read the model config (%s); parameter counts "
                  "in the plan will be 0." % exc)
            cfg = None

    counts, datasets = {}, {}
    if manifest:
        for key, rec in manifest.get("cells", {}).items():
            counts[key] = rec.get("n_samples", 0)
            datasets[key] = rec.get("dataset")
    else:
        cen = bcdata.census()
        for key, rec in cen["per_cell"].items():
            counts[key] = rec["verified_steps"]

    jobs, skipped = [], []
    for c in cell_list:
        n = counts.get(c.key, 0)
        if n <= 0:
            skipped.append(c.key)
            continue
        ds = datasets.get(c.key) or "adaptercl_%s_%s" % (tag, c.key)
        for ts in target_sets:
            for r in ranks:
                sites = targets.enumerate_sites(cfg, ts) if cfg else []
                sub_tag = tag if (len(target_sets) == 1 and len(ranks) == 1) \
                    else "%s_%s_r%d" % (tag, ts, r)
                out_dir = cell_output_dir(c, sub_tag)
                ypath = cell_yaml_path(c, sub_tag)
                job = CellJob(c, ds, ts, r, 2 * r, sub_tag, ypath, out_dir,
                              n_samples=n, epochs=epochs, grad_accum=grad_accum,
                              gpus=gpus, n_sites=len(sites),
                              n_params=targets.site_budget(sites, r) if sites else 0,
                              seed=seed)
                if write_yaml:
                    write_cell_yaml(c, ds, target_set=ts, rank=r, tag=sub_tag,
                                    out_dir=out_dir, yaml_path=ypath,
                                    epochs=epochs, grad_accum=grad_accum,
                                    n_samples=n, seed=seed, **yaml_kw)
                jobs.append(job)
    if skipped:
        print("SKIPPED %d cell(s) with no BC data: %s"
              % (len(skipped), ", ".join(skipped)))
        print("  (that is adapterCL.md 7 Phase 2's 18-cell design failing on "
              "the data that exists -- see `python -m adaptercl.bcdata census`)")
    return jobs


